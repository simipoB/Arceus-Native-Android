# romfs_files.py <out .h> <comment> <NAME>=<file> ...: game files kept in the engine library as byte arrays (written out on start and laid over the game's RomFS:
#   android_main.c lowspec / qol). NXZ1 entries (the APK's assets/gamez/, dm/android/compat/apkfs.c) are stored decompressed
import struct, sys, zlib

def nxz(b):
    if b[:4] != b'NXZ1': return b
    bs, raw, nb = struct.unpack_from('<IQI', b, 4)
    t = struct.unpack_from('<%dI' % (nb + 1), b, 20); base = 20 + 4 * (nb + 1); out = b''
    for i in range(nb):
        c = b[base + t[i]: base + t[i + 1]]
        out += c if len(c) == min(bs, raw - i * bs) else zlib.decompress(c)
    return out

def main():
    out, comment = sys.argv[1], sys.argv[2]
    lines = [f'// Generated by dm/tools/romfs_files.py: {comment}', '#pragma once', '']
    for arg in sys.argv[3:]:
        name, path = arg.split('=', 1); b = nxz(open(path, 'rb').read())
        lines.append(f'static const unsigned char {name}[{len(b)}] = {{')
        for i in range(0, len(b), 24): lines.append('    ' + ', '.join(f'0x{x:02x}' for x in b[i:i + 24]) + ',')
        lines += ['};', '']
    open(out, 'w', newline='\n').write('\n'.join(lines))

if __name__ == '__main__':
    main()
